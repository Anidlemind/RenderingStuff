#include "scene/scene.h"

Scene Scene::makeIcosahedron() {
  Scene s;

  const float phi = 1.618f;

  s.verts = {
    // (±1, ±φ, 0)
    {-1.0f,  phi,  0.0f, {255,   0,   0}},
    { 1.0f,  phi,  0.0f, {255,  64,   0}},
    {-1.0f, -phi,  0.0f, {255, 128,   0}},
    { 1.0f, -phi,  0.0f, {255, 192,   0}},

    // (0, ±1, ±φ)
    { 0.0f, -1.0f,  phi, {128, 255,   0}},
    { 0.0f,  1.0f,  phi, {  0, 255,   0}},
    { 0.0f, -1.0f, -phi, {  0, 255, 128}},
    { 0.0f,  1.0f, -phi, {  0, 255, 255}},

    // (±φ, 0, ±1)
    { phi,  0.0f, -1.0f, {  0, 128, 255}},
    { phi,  0.0f,  1.0f, {  0,   0, 255}},
    {-phi,  0.0f, -1.0f, {128,   0, 255}},
    {-phi,  0.0f,  1.0f, {255,   0, 255}},
  };

 s.tris = {
    // 5 граней вокруг вершины 0
    { 0, 11,  5},
    { 0,  5,  1},
    { 0,  1,  7},
    { 0,  7, 10},
    { 0, 10, 11},

    // 5 граней вокруг вершины 3
    { 3,  9,  4},
    { 3,  4,  2},
    { 3,  2,  6},
    { 3,  6,  8},
    { 3,  8,  9},

    // оставшиеся 10 граней
    {11,  4,  5},
    { 5,  4,  9},
    { 5,  9,  1},
    { 1,  9,  8},
    { 1,  8,  7},
    { 7,  8,  6},
    { 7,  6, 10},
    {10,  6,  2},
    {10,  2, 11},
    {11,  2,  4},
  };  

  s.model = Mat4::identity();
  return s;
}